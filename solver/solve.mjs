// Route solver for Monarch Compass.
//
// Treats "unlock everything in ARISE" as a planning problem. Each milestone has requirements
// (from the official guide's unlock conditions, data/milestones.json). Among the milestones whose
// requirements are met, the scorer in js/engine.js picks the best one for a spending plan, using
// the weights in MonarchEngine.WEIGHTS: daily farms first, then Total Power systems, free currency,
// seasonal content, and how many milestones each one leads to.
//
// Usage: node solver/solve.mjs           write data/route-solved.json and ROUTE.md for all 3 plans
//        node solver/solve.mjs --check   check the page's own order and every plan's route; exit 1 on a violation
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
await import(pathToFileURL(join(root, "js", "engine.js")).href);
const E = globalThis.MonarchEngine;
const { phases, milestones } = JSON.parse(readFileSync(join(root, "data", "milestones.json"), "utf8"));

// The engine works on the page's field names.
const MS = milestones.map(m => ({ id: m.id, ph: m.phase, req: m.requires, tags: m.tags, line: m.line, t: m.title }));
const byId = Object.fromEntries(milestones.map(m => [m.id, m]));
const PLANS = { f2p: "Free to play", light: "Light spender", spender: "Spender" };

let failed = false;
const report = (what, errs) => {
  if (errs.length) { failed = true; console.error(`${what}: ${errs.length} problem(s)\n  ` + errs.join("\n  ")); }
  else console.log(`${what}: valid (${MS.length} milestones)`);
};

// The page lists milestones in data order; that order must itself be playable.
report("Page order", E.check(MS, MS.map(m => m.id)));
const routes = {};
for (const p of Object.keys(PLANS)) {
  routes[p] = E.route(MS, {}, p);
  report(`${PLANS[p]} route`, E.check(MS, routes[p].map(r => r.id)));
}
if (failed) process.exit(1);
if (process.argv.includes("--check")) process.exit(0);

writeFileSync(join(root, "data", "route-solved.json"), JSON.stringify(
  Object.fromEntries(Object.entries(routes).map(([p, r]) => [p, r.map((s, i) => ({ step: i + 1, id: s.id, score: s.score, why: s.why }))])),
  null, 2) + "\n");

const phaseName = Object.fromEntries(phases.map(p => [p.id, p.title]));
let md = `# Monarch Compass route\n\nGenerated by \`node solver/solve.mjs\` from \`data/milestones.json\`. Do not edit by hand.\n\n` +
  `Each step is the best milestone available at that point for the plan. Score = sum of the weights below; ties keep story order.\n\n` +
  `| Signal | Free to play | Light | Spender | Why |\n|---|---:|---:|---:|---|\n` +
  Object.entries(E.WEIGHTS).map(([k, w]) => `| ${k} | ${w.f2p} | ${w.light} | ${w.spender} | ${w.why} |`).join("\n") + "\n";
for (const [p, name] of Object.entries(PLANS)) {
  md += `\n## ${name}\n\n| # | Milestone | Unlocks | Phase | Score | Signals |\n|---:|---|---|---|---:|---|\n`;
  md += routes[p].map((s, i) => {
    const m = byId[s.id];
    return `| ${i + 1} | ${m.title} | ${m.unlocks} | ${phaseName[m.phase]} | ${s.score} | ${s.why.join(", ")} |`;
  }).join("\n") + "\n";
}
md += `\n## What to do at each milestone\n`;
for (const m of milestones) {
  md += `\n### ${m.title}\n\nUnlocks: ${m.unlocks}. Requires: ${m.requires.map(r => byId[r].title).join(", ") || "nothing"}. Confidence: ${m.confidence}.\n\n` +
    m.todo.map((t, i) => `${i + 1}. ${t}`).join("\n") + "\n" + (m.warning ? `\n> ${m.warning}\n` : "");
}
writeFileSync(join(root, "ROUTE.md"), md);
console.log("Wrote data/route-solved.json and ROUTE.md");
